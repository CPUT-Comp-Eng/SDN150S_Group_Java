    private double getExchangeRate(String currency) {
    if (currency == null) return 1.0;
    
    switch (currency) { //in refrence point to USD
        case "Bitcoin (BTC)":  return 81673.80; 
        case "Ethereum (ETH)":  return 2399.68;
        case "Tether (USDT)": return 1.0;
        case "BNB (BNB)":  return 744.78;
        case "XRP (XRP)":  return 1.32;
        case "USD Coin (USDC)": return 1.0;
        case "Solana (SOL)":  return 104.41;
        case "TRON (TRX)":  return 0.32;
        case "Zcash (ZEC)":  return 1219.61;
        case "Hyperliquid (HYPE)": return 79;
        case "USD":  return 1.0;
        default:     return 1.0; 
    }
}
    
    
